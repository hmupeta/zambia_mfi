# Wallet Reconciliation
# ============================================================
RECONCILIATION_STATUS_CHOICES = [
    ('BALANCED', 'Balanced'),
    ('VARIANCE', 'Variance Found'),
    ('RESOLVED', 'Resolved'),
]


class WalletReconciliation(models.Model):
    """
    Records a physical cash/momo/bank count against the system balances
    in BranchWallet. Immutable snapshot at the time of reconciliation.
    """
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    organization = models.ForeignKey(
        Organization, on_delete=models.CASCADE,
        related_name='wallet_reconciliations', editable=False,
    )
    branch = models.ForeignKey(Branch, on_delete=models.CASCADE, related_name='wallet_reconciliations')
    reconciliation_number = models.CharField(max_length=40, unique=True, db_index=True)

    # System balances at reconciliation time (snapshot)
    system_cash = models.DecimalField(max_digits=14, decimal_places=2, default=0)
    system_momo = models.DecimalField(max_digits=14, decimal_places=2, default=0)
    system_bank = models.DecimalField(max_digits=14, decimal_places=2, default=0)
    system_total = models.DecimalField(max_digits=14, decimal_places=2, default=0)

    # Physical counts entered by the manager
    physical_cash = models.DecimalField(max_digits=14, decimal_places=2, default=0)
    physical_momo = models.DecimalField(max_digits=14, decimal_places=2, default=0)
    physical_bank = models.DecimalField(max_digits=14, decimal_places=2, default=0)
    physical_total = models.DecimalField(max_digits=14, decimal_places=2, default=0)

    # Variances = physical − system (positive = surplus, negative = shortage)
    variance_cash = models.DecimalField(max_digits=14, decimal_places=2, default=0)
    variance_momo = models.DecimalField(max_digits=14, decimal_places=2, default=0)
    variance_bank = models.DecimalField(max_digits=14, decimal_places=2, default=0)
    variance_total = models.DecimalField(max_digits=14, decimal_places=2, default=0)

    status = models.CharField(
        max_length=20, choices=RECONCILIATION_STATUS_CHOICES,
        default='BALANCED', db_index=True,
    )
    notes = models.TextField(blank=True)

    reconciled_by = models.ForeignKey(
        User, on_delete=models.SET_NULL, null=True, related_name='reconciliations_done',
    )
    reconciled_at = models.DateTimeField(auto_now_add=True)

    resolved_by = models.ForeignKey(
        User, on_delete=models.SET_NULL, null=True, blank=True,
        related_name='reconciliations_resolved',
    )
    resolved_at = models.DateTimeField(null=True, blank=True)
    resolution_notes = models.TextField(blank=True)

    class Meta:
        db_table = 'wallet_reconciliations'
        ordering = ['-reconciled_at']
        indexes = [
            models.Index(fields=['organization', '-reconciled_at']),
            models.Index(fields=['branch', '-reconciled_at']),
            models.Index(fields=['status']),
        ]

    def __str__(self):
        return f"{self.reconciliation_number} — {self.branch.code}"

    def save(self, *args, **kwargs):
        if self.branch_id and not self.organization_id:
            self.organization_id = self.branch.organization_id
        super().save(*args, **kwargs)

