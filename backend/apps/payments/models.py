from django.db import models
from apps.core.models import Organization, Branch, User
from apps.clients.models import Client
from apps.loans.models import Loan, LoanInstallment
import uuid


# ============================================================
# Choice Constants
# ============================================================
PAYMENT_METHOD_CHOICES = [
    ('CASH', 'Cash'),
    ('MTN_MOMO', 'MTN Mobile Money'),
    ('AIRTEL_MONEY', 'Airtel Money'),
    ('BANK', 'Bank'),
]

PAYMENT_TYPE_CHOICES = [
    ('INSTALLMENT', 'Installment'),
    ('PENALTY', 'Penalty'),
    ('PARTIAL', 'Partial'),
    ('BULK', 'Bulk'),
]

WALLET_TRANSACTION_TYPE_CHOICES = [
    ('DISBURSEMENT', 'Disbursement'),
    ('LOAN_COLLECTION', 'Loan Collection'),
    ('TRANSFER_IN', 'Transfer In'),
    ('TRANSFER_OUT', 'Transfer Out'),
    ('EXPENSE', 'Expense'),
]


# ============================================================
# Payment
# ============================================================
class Payment(models.Model):
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    organization = models.ForeignKey(
        Organization, on_delete=models.CASCADE,
        related_name='payments', editable=False,
    )
    payment_number = models.CharField(max_length=30)
    loan = models.ForeignKey(Loan, on_delete=models.PROTECT, related_name='payments')
    branch = models.ForeignKey(Branch, on_delete=models.PROTECT, related_name='payments')
    received_by = models.ForeignKey(User, on_delete=models.SET_NULL, null=True)
    client = models.ForeignKey(Client, on_delete=models.PROTECT, related_name='payments')

    amount = models.DecimalField(max_digits=12, decimal_places=2)

    payment_method = models.CharField(
        max_length=20,
        choices=PAYMENT_METHOD_CHOICES,
    )
    transaction_ref = models.CharField(max_length=100, blank=True)
    payment_type = models.CharField(
        max_length=20,
        choices=PAYMENT_TYPE_CHOICES,
        default='INSTALLMENT',
    )
    notes = models.TextField(blank=True)

    received_at = models.DateTimeField(auto_now_add=True)

    # Link to the GL journal entry generated by this payment
    journal_entry = models.OneToOneField(
        'accounting.JournalEntry',
        on_delete=models.SET_NULL,
        null=True, blank=True,
        related_name='source_payment',
        help_text='GL journal entry generated by this payment',
    )

    # ── Reversal tracking ─────────────────────────────
    is_reversed = models.BooleanField(default=False, db_index=True)
    reversed_at = models.DateTimeField(null=True, blank=True)
    reversed_by = models.ForeignKey(
        User, on_delete=models.SET_NULL, null=True, blank=True,
        related_name='reversed_payments',
    )
    reversal_reason = models.TextField(blank=True)
    reversal_journal_entry = models.OneToOneField(
        'accounting.JournalEntry',
        on_delete=models.SET_NULL,
        null=True, blank=True,
        related_name='reversal_for_payment',
        help_text='GL journal entry that reverses this payment',
    )
    group_collection = models.ForeignKey(
        'loans.GroupCollection', on_delete=models.SET_NULL,
        null=True, blank=True, related_name='payments',
    )

    class Meta:
        db_table = 'payments'
        ordering = ['-received_at']
        constraints = [
            models.UniqueConstraint(
                fields=['organization', 'payment_number'],
                name='unique_payment_number_per_org',
            ),
        ]

    def __str__(self):
        return f"{self.payment_number} - {self.client}"

    def save(self, *args, **kwargs):
        if self.loan_id and not self.organization_id:
            self.organization_id = self.loan.organization_id
        if self.loan_id and not self.branch_id:
            self.branch_id = self.loan.branch_id
        super().save(*args, **kwargs)


# ============================================================
# Payment Allocation
# ============================================================
class PaymentAllocation(models.Model):
    id = models.BigAutoField(primary_key=True)
    payment = models.ForeignKey(
        Payment, on_delete=models.CASCADE, related_name='allocations',
    )
    installment = models.ForeignKey(LoanInstallment, on_delete=models.CASCADE)

    principal_portion = models.DecimalField(max_digits=12, decimal_places=2)
    interest_portion = models.DecimalField(max_digits=12, decimal_places=2)
    penalty_portion = models.DecimalField(max_digits=12, decimal_places=2, default=0)

    allocated_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = 'payment_allocations'

    def __str__(self):
        return f"{self.payment.payment_number} - installment {self.installment.installment_no}"


